                        <!-- Tópico 2 -->
                        <h2>Principais sistemas GNSS disponíveis</h2>
                        <p>
                            Existem atualmente <strong>quatro sistemas globais</strong> de navegação por satélite:
                        </p>
                        <ul>
                            <li><strong>GPS (EUA)</strong> - O sistema mais antigo e amplamente utilizado, com 31 satélites em órbita.</li>
                            <li><strong>GLONASS (Rússia)</strong> - Sistema russo com 24 satélites, oferecendo boa cobertura em latitudes elevadas.</li>
                            <li><strong>Galileo (Europa)</strong> - Sistema europeu com 28 satélites, focado em aplicações civis.</li>
                            <li><strong>BeiDou (China)</strong> - Sistema chinês com 35 satélites, com cobertura global.</li>
                        </ul>
                        <p>
                            Além disso, existem sistemas regionais como o <strong>QZSS</strong> (Japão) e o 
                            <strong>IRNSS</strong> (Índia), que complementam os sistemas globais em regiões específicas.
                        </p>

                        <!-- Tópico 3 -->
                        <h2>Como o GNSS melhorou os levantamentos topográficos</h2>
                        <p>
                            A integração do GNSS nos levantamentos topográficos trouxe uma <strong>revolução</strong> 
                            na forma como os profissionais trabalham. Antes do GNSS, os levantamentos dependiam 
                            de <strong>estações totais</strong> e <strong>teodolitos</strong>, que exigiam 
                            linha de visão direta entre os pontos, limitando a eficiência em terrenos acidentados 
                            ou com obstáculos.
                        </p>
                        <p>
                            Com o GNSS, os topógrafos podem agora realizar levantamentos <strong>sem necessidade 
                            de linha de visão</strong>, em qualquer condição climática e em áreas de difícil acesso. 
                            A precisão alcançada com o GNSS é <strong>milimétrica</strong>, permitindo a criação 
                            de <strong>modelos digitais do terreno (MDT)</strong> e <strong>curvas de nível</strong> 
                            com uma qualidade nunca antes possível.
                        </p>

