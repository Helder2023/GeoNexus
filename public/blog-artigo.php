                        <!-- Tópico 1 -->
                        <h2>O que é GNSS e como funciona?</h2>
                        <p>
                            O GNSS é um sistema global de navegação por satélite que permite determinar 
                            a posição geográfica de um recetor em qualquer ponto da Terra. Atualmente, 
                            existem <strong>quatro sistemas principais</strong> em operação: o 
                            <strong>GPS</strong> (EUA), o <strong>GLONASS</strong> (Rússia), o 
                            <strong>Galileo</strong> (Europa) e o <strong>BeiDou</strong> (China). 
                            Todos esses sistemas trabalham em conjunto para fornecer uma precisão 
                            sem precedentes.
                        </p>
                        <p>
                            O funcionamento do GNSS baseia-se na <strong>triangulação de sinais</strong> 
                            emitidos por satélites em órbita. O recetor capta os sinais de, pelo menos, 
                            quatro satélites para calcular a sua posição em três dimensões (latitude, 
                            longitude e altitude). Com a evolução da tecnologia, a precisão dos sistemas 
                            GNSS atingiu níveis de <strong>centímetros ou até milímetros</strong>, 
                            tornando-os ferramentas indispensáveis para a topografia moderna.
                        </p>

                        <!-- Imagem -->
                        <div class="article-image">
